import type { SeoData } from '#lib/components/seo/seo-data.js';
import { breadcrumbSchema, jsonLd, webpageSchema } from '#lib/utils/site.js';
import type { PageServerLoad } from './$types';

const title = 'Privacy Policy | Room TBA';
const description =
	'See how Room TBA handles data, analytics, editor accounts and offline storage.';
const canonicalPath = '/privacy';

export const load: PageServerLoad = () => {
	const seo: SeoData = {
		title,
		description,
		canonicalPath,
		structuredData: jsonLd(
			webpageSchema({ title, description, path: canonicalPath }),
			breadcrumbSchema([
				{ name: 'Home', path: '/' },
				{ name: 'Privacy Policy', path: canonicalPath }
			])
		)
	};
	return { seo };
};
