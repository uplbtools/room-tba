import type { SeoData } from '#lib/components/seo/seo-data.js';
import { breadcrumbSchema, jsonLd, webpageSchema } from '#lib/utils/site.js';
import type { PageServerLoad } from './$types';

const title = 'Changelog | Room TBA';
const description =
	'Track recent Room TBA updates, including room data, course offerings, and site improvements.';
const canonicalPath = '/changelog';

export const load: PageServerLoad = () => {
	const seo: SeoData = {
		title,
		description,
		canonicalPath,
		structuredData: jsonLd(
			webpageSchema({ title, description, path: canonicalPath }),
			breadcrumbSchema([
				{ name: 'Home', path: '/' },
				{ name: 'Changelog', path: canonicalPath }
			])
		)
	};
	return { seo };
};
